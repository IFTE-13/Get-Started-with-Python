# The volume of a sphere with radius 𝑟 is given by the formula:
# V = (3/4)​πr^3

# Task: Calculate the volume of a sphere with radius 5.
# Radius of the sphere
radius = 5

# Value of pi
pi = 3.1416

# Calculate volume
volume = (4 / 3) * pi * (radius ** 3)

# Print result
print(f"The volume of a sphere with radius {radius} is: {volume:.2f}")
